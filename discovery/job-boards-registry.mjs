export function getJobBoardDetails(boardId) {
    if (!boardId) return null;
    return DIRECT_JOB_BOARDS_REGISTRY[String(boardId).toLowerCase()] || null;
}

export function getAllJobBoards() {
    return Object.values(DIRECT_JOB_BOARDS_REGISTRY);
}

export function getJobBoardsByStatus(status) {
    return Object.values(DIRECT_JOB_BOARDS_REGISTRY).filter(b => b.operational_status === status);
}
