// Read existing seed_companies.json and merge without duplicating
const seedPath = path.resolve('data/seed_companies.json');
let existingSeeds = [];
if (fs.existsSync(seedPath)) {
    try {
        existingSeeds = JSON.parse(fs.readFileSync(seedPath, 'utf8'));
    } catch {
        existingSeeds = [];
    }
}

const seenIds = new Set();
const seenDomains = new Set();
const merged = [];

// First add the structured verified employers
for (const emp of verifiedEmployers) {
    seenIds.add(emp.id);
    if (emp.domain) seenDomains.add(emp.domain.toLowerCase());
    merged.push(emp);
}

// Then merge remaining existing seeds
for (const seed of existingSeeds) {
    if (!seed || !seed.name) continue;
    const sId = seed.id || `company-${seed.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    const sDomain = (seed.domain || '').toLowerCase();

    if (seenIds.has(sId) || (sDomain && seenDomains.has(sDomain))) {
        continue;
    }

    seenIds.add(sId);
    if (sDomain) seenDomains.add(sDomain);

    merged.push({
        id: sId,
        name: seed.name,
        domain: seed.domain || null,
        career_url: seed.career_url || null,
        country: seed.country || 'Global',
        hiring_regions: seed.country ? [seed.country] : ['Global'],
        career_page_type: seed.ats_type ? 'ats_hosted' : 'custom_portal',
        ats_type: seed.ats_type || null,
        board_identifier: seed.board_identifier || null,
        fetch_mode: seed.ats_type ? 'api' : 'html_crawler',
        access_restrictions: 'public',
        verification_status: seed.lifecycle_status || 'VERIFIED',
        last_checked_at: new Date().toISOString(),
        last_successful_ingestion_at: null,
        aliases: seed.aliases || [],
        industry: seed.industry || 'Technology',
        size_band: seed.size_band || 'Unknown'
    });
}

const outPath = path.resolve('data/employer_registry.json');
fs.writeFileSync(outPath, JSON.stringify(merged, null, 2), 'utf8');
console.log(`Successfully compiled Employer Registry: ${merged.length} verified employers written to data/employer_registry.json`);
